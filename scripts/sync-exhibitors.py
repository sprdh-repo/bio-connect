#!/usr/bin/env python3
"""Write the exhibitor directory into the static website.

The directory used to load from the registration backend at page view. After
the event it is frozen: this script snapshots the backend's approved
exhibitors into the generated region of exhibitors.html and copies every logo
into assets/exhibitors/, so the page is plain static HTML that keeps working
without the backend. It is run by hand, not by scripts/deploy.sh.

Usage:
    python3 scripts/sync-exhibitors.py [--api URL] [--check]

--check exits 1 without writing anything when the page is out of date.

Logos are fitted inside 640 x 280 (twice the card's display size) and saved
as WebP under a name carrying the source's content hash, so a replaced logo
gets a new URL and no cache can serve the old one.
"""
import argparse
import hashlib
import html
import io
import json
import re
import sys
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
API = "https://reg.bioconnect.kerala.gov.in/api/v1/public/exhibitors"
LOGOS = ROOT / "assets" / "exhibitors"
LOGO_BOX = (640, 280)
LOGO_PATH = re.compile(r"^/api/v1/public/exhibitors/logos/[a-zA-Z0-9_-]+$")

BEGIN, END = "<!-- exhibitors:begin (generated by scripts/sync-exhibitors.py) -->", "<!-- exhibitors:end -->"


def fetch(url, limit=10 << 20):
    req = urllib.request.Request(url, headers={"User-Agent": "bioconnect-site-build"})
    with urllib.request.urlopen(req, timeout=30) as res:
        body = res.read(limit + 1)
    if len(body) > limit:
        sys.exit(f"{url} is larger than {limit} bytes")
    return body


def text(value):
    return html.escape(value, quote=False)


def attr(value):
    return html.escape(value, quote=True)


def logo_file(exhibitor, api, write):
    """Return the logo's file name and size in assets/exhibitors/, fetching it if new."""
    if not exhibitor["logo_url"]:
        return None
    url = urllib.parse.urljoin(api, exhibitor["logo_url"])
    parsed = urllib.parse.urlsplit(url)
    if parsed.netloc != urllib.parse.urlsplit(api).netloc or not LOGO_PATH.match(parsed.path):
        sys.exit(f"exhibitor {exhibitor['id']}: {url} is not the backend's public logo route")
    body = fetch(url)
    name = f"{exhibitor['id']}-{hashlib.sha256(body).hexdigest()[:10]}.webp"
    path = LOGOS / name
    if not path.exists():
        if not write:
            sys.exit(f"out of date: logo {path.relative_to(ROOT)} is missing; run scripts/sync-exhibitors.py")
        LOGOS.mkdir(parents=True, exist_ok=True)
        path.write_bytes(to_webp(body, url))
        print(f"added logo {path.relative_to(ROOT)}")
    return name, webp_size(path)


def to_webp(body, url):
    try:
        from PIL import Image, ImageOps
    except ImportError:
        sys.exit(f"{url} needs converting to WebP; install Pillow (pip install pillow)")
    im = ImageOps.exif_transpose(Image.open(io.BytesIO(body)))
    im = im.convert("RGBA" if im.mode in ("RGBA", "LA", "P") else "RGB")
    im.thumbnail(LOGO_BOX, Image.LANCZOS)
    out = io.BytesIO()
    im.save(out, "WEBP", quality=88, method=6)
    return out.getvalue()


def webp_size(path):
    from PIL import Image
    with Image.open(path) as im:
        return im.size


def monogram(name):
    return "".join(word[0] for word in name.split()[:2])


def card(exhibitor, logo):
    if logo:
        (file, (width, height)) = logo
        mark = f'<img src="assets/exhibitors/{attr(file)}" width="{width}" height="{height}" alt="" loading="lazy" decoding="async" />'
    else:
        mark = f'<span class="exhibitor-monogram" aria-hidden="true">{text(monogram(exhibitor["name"]))}</span>'
    return "\n".join([
        f'            <li class="exhibitor-card" data-exhibitor-id="{attr(exhibitor["id"])}">',
        f'              <div class="exhibitor-logo">{mark}</div>',
        '              <div class="exhibitor-meta">',
        '                <span class="detail-label">Confirmed exhibitor</span>',
        f'                <h3>{text(exhibitor["name"].strip())}</h3>',
        f'                <p class="exhibitor-description">{text(exhibitor["description"].strip())}</p>',
        "              </div>",
        "            </li>",
    ])


def replace_region(page, begin, end, body, indent):
    pattern = re.compile(re.escape(begin) + r".*?" + re.escape(end), re.S)
    if len(pattern.findall(page)) != 1:
        sys.exit(f"expected exactly one {begin} ... {end} region")
    return pattern.sub(lambda _: f"{begin}\n{body}\n{indent}{end}", page)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--api", default=API)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    exhibitors = json.loads(fetch(args.api))["exhibitors"]
    # An empty list is far more likely a backend fault than the real line-up.
    if not exhibitors:
        sys.exit("the exhibitor list is empty; refusing to publish a page without exhibitors")
    logos = {e["id"]: logo_file(e, args.api, not args.check) for e in exhibitors}

    path = ROOT / "exhibitors.html"
    page = path.read_text(encoding="utf-8")
    cards = "\n".join(card(e, logos[e["id"]]) for e in exhibitors)
    updated = replace_region(page, BEGIN, END, cards, "            ")
    if updated != page and args.check:
        sys.exit("out of date: exhibitors.html; run scripts/sync-exhibitors.py")
    if updated != page:
        path.write_text(updated, encoding="utf-8")
    print(f"{len(exhibitors)} exhibitors; " + ("updated exhibitors.html" if updated != page else "page already current"))


if __name__ == "__main__":
    main()
