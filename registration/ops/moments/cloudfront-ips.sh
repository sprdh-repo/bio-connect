#!/usr/bin/env bash
set -euo pipefail
# Daily, from bioconnect-cloudfront-ips.timer. Rewrites the Apache allow-list
# for the BioConnect vhost from AWS's published CloudFront origin-facing ranges.
# Apache is reloaded only when the list changed and the whole config tests clean;
# otherwise the previous list is put back, so other sites on this host are never
# left with a broken config.
target=/etc/httpd/conf/extra/bioconnect-cloudfront-ips.conf
new=$(mktemp)
trap 'rm -f "$new"' EXIT
curl --fail --silent --show-error --max-time 30 https://ip-ranges.amazonaws.com/ip-ranges.json | python -c '
import json, sys
d = json.load(sys.stdin)
v4 = sorted(set(p["ip_prefix"] for p in d["prefixes"] if p["service"] == "CLOUDFRONT_ORIGIN_FACING"))
v6 = sorted(set(p["ipv6_prefix"] for p in d["ipv6_prefixes"] if p["service"] == "CLOUDFRONT_ORIGIN_FACING"))
if len(v4) < 10:
    sys.exit("suspiciously few CloudFront origin-facing ranges: %d" % len(v4))
print("# Generated by /opt/bioconnect-ops/cloudfront-ips.sh from ip-ranges.amazonaws.com. Do not edit.")
print("<RequireAny>")
for p in v4 + v6:
    print("    Require ip " + p)
print("</RequireAny>")
' > "$new"
if [[ -f "$target" ]] && cmp -s "$new" "$target"; then
  exit 0
fi
backup=$(mktemp)
[[ -f "$target" ]] && cp -p "$target" "$backup"
install -m 644 -o root -g root "$new" "$target"
if /usr/sbin/httpd -t > /dev/null 2>&1; then
  /usr/sbin/httpd -k graceful
  logger -t bioconnect-cloudfront-ips "CloudFront origin-facing ranges updated"
else
  [[ -s "$backup" ]] && install -m 644 -o root -g root "$backup" "$target"
  rm -f "$backup"
  logger -p daemon.err -t bioconnect-cloudfront-ips "Apache config test failed; kept the previous ranges"
  exit 1
fi
rm -f "$backup"
